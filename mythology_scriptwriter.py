def get_story(key: str = "karna_secret") -> dict:
    key = key.lower()
    for k, v in MAHABHARAT_STORIES.items():
        if k in key or key in k:
            return v

    # Fallback to dynamic content catalog from content_engine
    try:
        from content_engine import STORY_CATALOG
        for item in STORY_CATALOG:
            if item["id"] in key or key in item["id"]:
                if item.get("is_series") and "parts" in item:
                    # Return the requested part or part 1
                    part_num = 2 if "part_02" in key or "part_2" in key else 1
                    p = item["parts"][part_num - 1]
                    return {
                        "topic": item["title"],
                        "series_title": "MYTHOLOGY SERIAL",
                        "top_hook": p["top_hook"],
                        "top_hook_hindi": p["top_hook_hindi"],
                        "beats": p["beats"],
                        "caption": f"⚡ {p['top_hook_hindi']}\n\nFollow @untold_mythology_legends for daily authentic Hindu legends!\n\n#sanatandharma #reelsindia"
                    }
                else:
                    return {
                        "topic": item["title"],
                        "series_title": "UNTOLD MYTHOLOGY",
                        "top_hook": item["top_hook"],
                        "top_hook_hindi": item["top_hook_hindi"],
                        "beats": item["beats"],
                        "caption": f"🔱 {item['top_hook_hindi']}\n\nFollow @untold_mythology_legends!\n\n#sanatan #mythology #reels"
                    }
    except Exception as e:
        print("[!] Content engine catalog lookup note:", e)

    return MAHABHARAT_STORIES["karna_secret"]

def list_all_keys() -> list:
    keys = list(MAHABHARAT_STORIES.keys())
    try:
        from content_engine import STORY_CATALOG
        for item in STORY_CATALOG:
            if item.get("is_series") and "parts" in item:
                for idx in range(len(item["parts"])):
                    keys.append(f"{item['id']}_part_{idx+1:02d}")
            else:
                keys.append(f"reel_{item['id']}")
    except Exception:
        pass
    return keys
